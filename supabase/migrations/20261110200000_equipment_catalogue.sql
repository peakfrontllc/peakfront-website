-- Standard heavy-equipment types and the sizes rented under each one.
-- Existing categories are left in place. A type or size is added only when that name is missing.

insert into public.equipment_categories (name, slug, description, tonnage)
select seed.name, seed.slug, '', ''
from (
  values
    ('Pickup Crane', 'pickup-crane'),
    ('Wheel Loader', 'wheel-loader'),
    ('Backhoe Loader', 'backhoe-loader'),
    ('Bulldozer', 'bulldozer'),
    ('Motor Grader', 'motor-grader'),
    ('Roller', 'roller'),
    ('Skid Steer', 'skid-steer'),
    ('Telehandler', 'telehandler'),
    ('Forklift', 'forklift'),
    ('Mobile Crane', 'mobile-crane'),
    ('Rough Terrain Crane', 'rough-terrain-crane'),
    ('Boom Lift', 'boom-lift'),
    ('Scissor Lift', 'scissor-lift'),
    ('Tipper Truck', 'tipper-truck'),
    ('Water Tanker', 'water-tanker'),
    ('Fuel Tanker', 'fuel-tanker'),
    ('Low Bed Trailer', 'low-bed-trailer'),
    ('Flatbed Truck', 'flatbed-truck'),
    ('Generator', 'generator'),
    ('Diesel Pump', 'diesel-pump'),
    ('Air Compressor', 'air-compressor'),
    ('Lighting Tower', 'lighting-tower'),
    ('Bus', 'bus')
) as seed(name, slug)
where not exists (
  select 1 from public.equipment_categories existing
  where existing.parent_id is null and lower(existing.name) = lower(seed.name)
)
and not exists (
  select 1 from public.equipment_categories existing where existing.slug = seed.slug
);

